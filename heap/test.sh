#!/bin/bash

# Скрипт для швидкого тестування лабораторної роботи №5

echo "═══════════════════════════════════════════════════════"
echo "  ТЕСТУВАННЯ ЛАБОРАТОРНОЇ РОБОТИ №5 - ПІРАМІДИ"
echo "═══════════════════════════════════════════════════════"
echo ""

# Перевірка наявності виконуваних файлів
if [ ! -f "./Lab_05_01" ] || [ ! -f "./Lab_05_02" ]; then
    echo "Виконувані файли не знайдено. Виконую компіляцію..."
    make all
    if [ $? -ne 0 ]; then
        echo "❌ Помилка компіляції!"
        exit 1
    fi
    echo ""
fi

# Функція для запуску тесту
run_test() {
    local test_name=$1
    local program=$2
    local input=$3
    
    echo "─────────────────────────────────────────────────────"
    echo "▶ Тест: $test_name"
    echo "─────────────────────────────────────────────────────"
    echo ""
    echo "$input" | $program
    echo ""
}

# Меню вибору
echo "Оберіть режим тестування:"
echo "1) Запустити Lab_05_01 (Побудова піраміди та сортування)"
echo "2) Запустити Lab_05_02 (Черга з пріоритетами)"
echo "3) Автоматичний тест базових функцій"
echo "4) Перекомпілювати проекти"
echo "0) Вихід"
echo ""
read -p "Ваш вибір: " choice

case $choice in
    1)
        echo ""
        echo "Запуск Lab_05_01..."
        echo "─────────────────────────────────────────────────────"
        ./Lab_05_01
        ;;
    2)
        echo ""
        echo "Запуск Lab_05_02..."
        echo "─────────────────────────────────────────────────────"
        ./Lab_05_02
        ;;
    3)
        echo ""
        echo "Автоматичне тестування базових функцій..."
        echo ""
        
        # Тест 1: Max-Heap та сортування
        echo "═══ ТЕСТ 1: Побудова Max-Heap ═══"
        echo -e "1\n5\n4\n10\n3\n5\n1\n3\n2\n0" | ./Lab_05_01
        
        echo ""
        echo "═══ ТЕСТ 2: Min-Heap ═══"
        echo -e "1\n5\n7\n3\n9\n1\n5\n4\n2\n0" | ./Lab_05_01
        
        echo ""
        echo "✓ Автоматичні тести завершено"
        ;;
    4)
        echo ""
        echo "Перекомпіляція проектів..."
        make rebuild
        ;;
    0)
        echo "Вихід."
        exit 0
        ;;
    *)
        echo "❌ Невірний вибір!"
        exit 1
        ;;
esac

echo ""
echo "═══════════════════════════════════════════════════════"
echo "  Тестування завершено"
echo "═══════════════════════════════════════════════════════"
